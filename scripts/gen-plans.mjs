// Derives src/plans.generated.ts from api-data/openapi.yaml (`x-flipzi-plan` on each operation),
// so the MCP server's plan requirements cannot drift from the API's own contract.
// Usage: node scripts/gen-plans.mjs [--check] [--spec=path]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const specArg = process.argv.find((a) => a.startsWith('--spec='));
const spec = specArg ? specArg.slice(7) : resolve(here, '../../api-data/openapi.yaml');
const out = resolve(here, '../src/plans.generated.ts');
const check = process.argv.includes('--check');

if (!existsSync(spec)) {
  if (check) { console.log('openapi.yaml not found next to this repo; skipping drift check'); process.exit(0); }
  console.error('spec not found: ' + spec); process.exit(1);
}
const lines = readFileSync(spec, 'utf8').split('\n');
const ops = {};
let version = '';
let inInfo = false;
for (let i = 0; i < lines.length; i++) {
  const l = lines[i];
  if (/^info:/.test(l)) inInfo = true;
  const v = inInfo && l.match(/^\s{2}version:\s*["']?([\d.]+)/);
  if (v && !version) version = v[1];
  const m = l.match(/^\s+operationId:\s*(\w+)/);
  if (m) {
    const p = lines[i + 1] && lines[i + 1].match(/x-flipzi-plan:\s*(\{.*\})\s*(#.*)?$/);
    if (p) ops[m[1]] = JSON.parse(p[1]);
  }
}
if (!version || !Object.keys(ops).length) { console.error('could not parse spec'); process.exit(1); }
const sorted = Object.fromEntries(Object.entries(ops).sort(([a], [b]) => a.localeCompare(b)));
const body = `// GENERATED by scripts/gen-plans.mjs from api-data/openapi.yaml. Do not edit.
export const SPEC_VERSION = ${JSON.stringify(version)};
export interface PlanReq { min_plan: string; feature: string | null; units: number | string }
export const OPS: Record<string, PlanReq> = ${JSON.stringify(sorted, null, 2)};
`;
if (check) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (cur !== body) { console.error('src/plans.generated.ts is stale: run npm run gen:plans'); process.exit(1); }
  console.log('plans.generated.ts matches openapi.yaml ' + version);
} else {
  writeFileSync(out, body);
  console.log('wrote ' + out + ' (' + Object.keys(sorted).length + ' operations, spec ' + version + ')');
}
